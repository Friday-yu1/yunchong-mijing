/* ---------- 归一化 & 全局导出 ---------- */
(function () {
  function familyOf(latin) {
    var first = latin.split(/\s+/)[0].replace(/[,.]$/, '');
    return YC_FAMILY[first] || '待鉴定';
  }
  function genusOf(latin) {
    var parts = latin.split(/\s+/);
    if (/gen\.\s*sp\.?/i.test(latin)) return '待鉴定';
    return parts[0] || '待鉴定';
  }
  function tbdOf(sp) {
    return sp.name.indexOf('待鉴定') !== -1 || sp.latin.indexOf('待鉴定') !== -1;
  }

  var species = YC_RAW_SPECIES.map(function (r) {
    var okey = YC_ORDER_KEY[r.order];
    return {
      id: 'sp-' + String(r.id).padStart(3, '0'),
      num: r.id,
      zh: r.name,
      latin: r.latin,
      order: okey,
      orderLabel: okey ? (YC_ORDERS.find(function (o) { return o.key === okey; }) || {}).label : r.order,
      band: YC_STATION_KEY[r.station] || 'widespread',
      protect: r.status,
      photo: r.photo,
      family: familyOf(r.latin),
      genus: genusOf(r.latin),
      tbd: tbdOf(r)
    };
  });

  var byId = {};
  species.forEach(function (s) { byId[s.id] = s; });

  var bandMap = {};
  YC_BANDS.forEach(function (b) { bandMap[b.key] = b; });

  window.YC = {
    orders: YC_ORDERS,
    bands: YC_BANDS,
    species: species,
    byId: byId,
    bandMap: bandMap,
    morph: YC_MORPH,
    morphSpecies: YC_MORPH_SPECIES,
    orderCode: YC_ORDER_CODE,
    detail: YC_DETAIL,
    habit: YC_HABIT,
    hotspots: YC_HOTSPOTS,
    distNote: YC_DIST_NOTE,
    orderLabel: function (key) {
      var o = YC_ORDERS.find(function (x) { return x.key === key; });
      return o ? o.label : key;
    }
  };
})();
